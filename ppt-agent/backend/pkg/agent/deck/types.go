func (m *TasksManifest) MustMarshalJSON() ([]byte, error) {
	data, err := json.Marshal(m)
	if err != nil {
		logger.Error("tasks_manifest_marshal_failed", "error", err.Error())
		return nil, err
	}
	return data, nil
}

func (m *TasksManifest) UnmarshalJSON(data []byte) error {
	type alias TasksManifest
	return json.Unmarshal(data, (*alias)(m))
}

func (m *TasksManifest) CompletedCount() int {
	count := 0
	for _, t := range m.Tasks {
		if t.Status == StatusDone || t.Status == StatusQADone || t.Status == StatusFixed {
			count++
		}
	}
	return count
}

func (m *TasksManifest) AllDone() bool {
	return m.CompletedCount() == len(m.Tasks) && len(m.Tasks) > 0
}

func (m *TasksManifest) NeedsFix() []*TaskItem {
	return nil
}

func (m *TasksManifest) PendingTasks() []*TaskItem {
	var result []*TaskItem
	for _, t := range m.Tasks {
		if t.Status == StatusPending {
			result = append(result, t)
		}
	}
	return result
}

func (m *TasksManifest) DoneTasks() []*TaskItem {
	var result []*TaskItem
	for _, t := range m.Tasks {
		if t.Status == StatusDone {
			result = append(result, t)
		}
	}
	return result
}

func (m *TasksManifest) GetTask(taskID string) *TaskItem {
	for _, t := range m.Tasks {
		if t.TaskID == taskID {
			return t
		}
	}
	return nil
}

func WriteTasksManifest(workDir string, manifest *TasksManifest) error {
	tasksManifestMu.Lock()
	defer tasksManifestMu.Unlock()

	// 读取现有数据以补齐调用方没有携带的运行时状态。调用方显式传入的新
	// status 必须被尊重，否则 done 会被旧的 pending 覆盖。
	data, err := os.ReadFile(filepath.Join(workDir, "tasks.json"))
	if err != nil && !os.IsNotExist(err) {
		return err
	}

	if len(data) > 0 {
		existing := &TasksManifest{}
		if err := existing.UnmarshalJSON(data); err == nil && existing.Tasks != nil && manifest.Tasks != nil {
			for i, t := range manifest.Tasks {
				for _, et := range existing.Tasks {
					if t.TaskID == et.TaskID {
						if t.Status == "" {
							manifest.Tasks[i].Status = et.Status
						}
						break
					}
				}
			}
		}
	}

	return writeTasksManifestUnlocked(workDir, manifest)
}

func writeTasksManifestUnlocked(workDir string, manifest *TasksManifest) error {
	filePath := filepath.Join(workDir, "tasks.json")
	tmpPath := filePath + ".tmp"

	content, err := manifest.MustMarshalJSON()
	if err != nil {
		return err
	}
	if err := json.Unmarshal(content, &TasksManifest{}); err != nil {
		return fmt.Errorf("tasks manifest produced invalid JSON: %w", err)
	}
	if err := os.WriteFile(tmpPath, content, 0644); err != nil {
		return err
	}
	if err := os.Rename(tmpPath, filePath); err != nil {
		os.Remove(tmpPath)
		return err
	}
	return nil
}

// PatchTaskRuntimeFields updates one task's runtime-only fields under the same
// manifest lock used by WriteTasksManifest. Worker-pool rendering calls this
// instead of rewriting the full planning contract from concurrent goroutines.
func PatchTaskRuntimeFields(workDir, taskID, status string) error {
	tasksManifestMu.Lock()
	defer tasksManifestMu.Unlock()

	data, err := os.ReadFile(filepath.Join(workDir, "tasks.json"))
	if err != nil {
		return err
	}
	manifest := &TasksManifest{}
	if err := manifest.UnmarshalJSON(data); err != nil {
		return err
	}
	var found bool
	for _, task := range manifest.Tasks {
		if task == nil || task.TaskID != taskID {
			continue
		}
		found = true
		if status != "" {
			task.Status = status
		}
		break
	}
	if !found {
		return fmt.Errorf("task_id %s not found in tasks.json", taskID)
	}
	return writeTasksManifestUnlocked(workDir, manifest)
}

// ReconcileTasksManifestOutputFiles normalizes uniquely identifiable page
// artifacts to their declared output_file and marks present outputs as done.
func ReconcileTasksManifestOutputFiles(workDir string) (*TasksManifest, error) {
	manifest, err := ReadTasksManifest(workDir)
	if err != nil || manifest == nil {
		return manifest, err
	}
	changed := false
	for _, t := range manifest.Tasks {
		if t == nil || t.OutputFile == "" {
			continue
		}
		ready, err := reconcileTaskOutputFile(workDir, t)
		if err != nil {
			return nil, err
		}
		if ready && t.Status != StatusDone && t.Status != StatusQADone && t.Status != StatusFixed {
			t.Status = StatusDone
			changed = true
		}
	}
	if changed {
		if err := WriteTasksManifest(workDir, manifest); err != nil {
			return nil, err
		}
	}
	return manifest, nil
}

func reconcileTaskOutputFile(workDir string, task *TaskItem) (bool, error) {
	targetPath := filepath.Join(workDir, task.OutputFile)
	if _, err := os.Stat(targetPath); err == nil {
		return true, nil
	} else if !os.IsNotExist(err) {
		return false, err
	}

	candidates, err := pageOutputCandidates(workDir, task.PageIndex)
	if err != nil {
		return false, err
	}
	if len(candidates) != 1 {
		return false, nil
	}

	sourceName := candidates[0]
	sourcePath := filepath.Join(workDir, sourceName)
	if err := os.Rename(sourcePath, targetPath); err != nil {
		return false, fmt.Errorf("normalize output file %q to %q: %w", sourceName, task.OutputFile, err)
	}
	if err := renameRenderedThumbnail(workDir, sourceName, task.OutputFile); err != nil {
		return false, err
	}
	return true, nil
}

func pageOutputCandidates(workDir string, pageIndex int) ([]string, error) {
	if pageIndex <= 0 {
		return nil, nil
	}
	entries, err := os.ReadDir(workDir)
	if err != nil {
		return nil, err
	}
	underscorePrefix := fmt.Sprintf("%d_", pageIndex)
	dashPrefix := fmt.Sprintf("%d-", pageIndex)
	var candidates []string
	for _, entry := range entries {
		name := entry.Name()
		lowerName := strings.ToLower(name)
		if entry.IsDir() || filepath.Ext(lowerName) != ".pptx" {
			continue
		}
		if strings.HasPrefix(name, underscorePrefix) || strings.HasPrefix(name, dashPrefix) {
			candidates = append(candidates, name)
		}
	}
	return candidates, nil
}

func renameRenderedThumbnail(workDir, sourceFile, targetFile string) error {
	sourceStem := strings.TrimSuffix(filepath.Base(sourceFile), filepath.Ext(sourceFile))
	targetStem := strings.TrimSuffix(filepath.Base(targetFile), filepath.Ext(targetFile))
	if sourceStem == targetStem {
		return nil
	}
	qaDir := filepath.Join(workDir, "qa_images")
	sourcePath := filepath.Join(qaDir, sourceStem+".jpg")
	targetPath := filepath.Join(qaDir, targetStem+".jpg")
	if _, err := os.Stat(sourcePath); err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	if _, err := os.Stat(targetPath); err == nil {
		return nil
	} else if !os.IsNotExist(err) {
		return err
	}
	if err := os.Rename(sourcePath, targetPath); err != nil {
		return fmt.Errorf("normalize thumbnail %q to %q: %w", filepath.Base(sourcePath), filepath.Base(targetPath), err)
	}
	return nil
}

func ValidateTasksManifestOutcome(workDir string) (*ManifestValidationReport, error) {
	manifest, err := ReadTasksManifest(workDir)
	if err != nil {
		return nil, err
	}
	report := &ManifestValidationReport{
		Total: len(manifest.Tasks),
		Done:  manifest.CompletedCount(),
	}
	for _, t := range manifest.Tasks {
		if t == nil {
			continue
		}
		if t.Status != StatusDone && t.Status != StatusQADone && t.Status != StatusFixed {
			report.PendingTasks = append(report.PendingTasks, t.TaskID)
		}
		if t.OutputFile != "" {
			if _, err := os.Stat(filepath.Join(workDir, t.OutputFile)); err != nil {
				report.MissingFiles = append(report.MissingFiles, t.OutputFile)
			}
		}
	}
	report.Invalid = report.Total == 0 || len(report.PendingTasks) > 0 || len(report.MissingFiles) > 0
	return report, nil
}

func ReadTasksManifest(workDir string) (*TasksManifest, error) {
	data, err := os.ReadFile(filepath.Join(workDir, "tasks.json"))
	if err != nil {
		return nil, err
	}
	m := &TasksManifest{}
	if err := m.UnmarshalJSON(data); err != nil {
		return nil, err
	}
	return m, nil
}

