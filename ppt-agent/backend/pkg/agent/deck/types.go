// tasksManifestMu 保护 tasks.json 的并发读写，防止多个 goroutine（如 HTTP handlers）调用 WriteTasksManifest 时产生竞态
var tasksManifestMu sync.Mutex

// PPTTaskConfig PPT 任务配置
