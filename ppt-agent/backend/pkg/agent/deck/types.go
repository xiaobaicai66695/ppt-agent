// ContentPlan 描述单页幻灯片的组件级内容规划。
type ContentPlan struct {
	Summary       string          `json:"summary,omitempty"`        // one-sentence core summary
	SlideIntent   string          `json:"slide_intent,omitempty"`   // semantic goal of this page in the deck
	SectionNumber string          `json:"section_number,omitempty"` // section_divider chapter number, not page index
	EvidenceRefs  []string        `json:"evidence_refs,omitempty"`  // refs into deck-level content_bank for granular repair
	VisualIntent  *VisualIntent   `json:"visual_intent,omitempty"`  // visual role and asset intent for this slide
	Components    []PlanComponent `json:"components,omitempty"`     // executable semantic component plan
}

// VisualIntent describes why a slide should use a given visual treatment.
type VisualIntent struct {
	Role             string `json:"role,omitempty"`              // hero_photo, supporting_photo, map, chart, icon, cards
	AssetPurpose     string `json:"asset_purpose,omitempty"`     // background, scene, evidence, decorative
	AssetSubject     string `json:"asset_subject,omitempty"`     // visual subject or semantic proxy selected for search
	AssetQuery       string `json:"asset_query,omitempty"`       // transformed provider-ready image search phrase
	Composition      string `json:"composition,omitempty"`       // wide/close-up, negative space and subject placement
	Provider         string `json:"provider,omitempty"`          // asset provider that resolved the local file
	SearchStatus     string `json:"search_status,omitempty"`     // resolved or downloaded after provider search
	PreferredVariant string `json:"preferred_variant,omitempty"` // matching layout_variant when known
	ImagePosition    string `json:"image_position,omitempty"`    // background, left, right, strip, inline
	Caption          string `json:"caption,omitempty"`           // short caption or alt text
	AssetID          string `json:"asset_id,omitempty"`          // selected local asset id when available
	LocalPath        string `json:"local_path,omitempty"`        // downloaded image path in task work dir
	ImageURL         string `json:"image_url,omitempty"`         // provider image URL for preview/trace
	PreviewURL       string `json:"preview_url,omitempty"`       // provider thumbnail URL
	SourceURL        string `json:"source_url,omitempty"`        // source page for attribution
	Attribution      string `json:"attribution,omitempty"`       // human-readable attribution
}

